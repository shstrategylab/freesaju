  function getJieqi(year) {
    return JIEQI[year] || JIEQI.default;
  }

  function addJieqi(year, arr) {
    if (!Array.isArray(arr) || arr.length !== 12)
      throw new Error('입절일 배열은 12개여야 합니다.');
    JIEQI[year] = arr;
  }

